KINDS = ('npm', 'nginx')
CONTAINERS = {'npm': 'vw-panel-npm', 'nginx': 'vw-panel-nginx'}
NPM_IMAGE = 'jc21/nginx-proxy-manager:2.16.0'
NGINX_IMAGE = 'nginx:stable-alpine'
CERTBOT_IMAGE = 'certbot/certbot:latest'
MARKER = '# Generated by VW Panel\n'


def bootstrap_nginx(domain):
    return MARKER + '''server {
 listen 80;
 server_name %s;
 location /.well-known/acme-challenge/ { root /var/www/certbot; }
 location / { return 503; }
}
''' % domain


def https_nginx(domain):
    return MARKER + '''map $http_upgrade $vw_connection_upgrade { default upgrade; '' close; }
server {
 listen 80;
 server_name %(domain)s;
 location /.well-known/acme-challenge/ { root /var/www/certbot; }
 location / { return 301 https://$host$request_uri; }
}
server {
 listen 443 ssl;
 server_name %(domain)s;
 ssl_certificate /etc/letsencrypt/live/%(domain)s/fullchain.pem;
 ssl_certificate_key /etc/letsencrypt/live/%(domain)s/privkey.pem;
 client_max_body_size 128m;
 location / {
  proxy_pass http://vaultwarden:80;
  proxy_http_version 1.1;
  proxy_set_header Host $host;
  proxy_set_header X-Real-IP $remote_addr;
  proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
  proxy_set_header X-Forwarded-Proto $scheme;
  proxy_set_header Upgrade $http_upgrade;
  proxy_set_header Connection $vw_connection_upgrade;
  proxy_read_timeout 3600s;
 }
}
''' % {'domain': domain}


def ensure_proxy_ports(kind, folder, admin_port=None):
    """Only reuse containers whose bind mounts belong to this managed directory."""
    name = CONTAINERS[kind]
    running = False
    for candidate in ([name, 'vw-panel-certbot'] if kind=='nginx' else [name]):
        try:
            result = docker(['inspect', '--format', CONTAINER_FORMAT, candidate])
            if result.returncode == 0:
                info = json.loads(result.stdout)
                owned = any(Path(m.get('Source', '')).resolve().is_relative_to(folder.resolve()) for m in info.get('mounts', []))
                if not owned:raise ValueError('已有同名容器 %s，已保留原容器，请使用已有反代接入。' % candidate)
                if candidate==name:running=info.get('running') is True
        except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
            pass
    if running:return
    ports = {80, 443} | ({admin_port} if admin_port else set())
    occupied = set()
    for port in ports:
        for family, address in ((socket.AF_INET, '0.0.0.0'), (socket.AF_INET6, '::')):
            try:
                with socket.socket(family, socket.SOCK_STREAM) as probe:
                    if family == socket.AF_INET6:probe.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
                    probe.bind((address, port))
            except OSError as error:
                import errno
                if error.errno == errno.EADDRINUSE:occupied.add(port)
    try:
        rows = docker(['ps', '--format', '{{json .}}'])
        if rows.returncode == 0:
            for line in rows.stdout.splitlines():
                row = json.loads(line)
                if row.get('Names') == name:continue
                occupied.update(int(p) for p in re.findall(r':(\d+)->', row.get('Ports', '')) if int(p) in ports)
    except (OSError, subprocess.SubprocessError, ValueError):
        pass
    if occupied:raise ValueError('端口 %s 已被占用，请使用已有反代或调整管理端口。' % ' / '.join(map(str, sorted(occupied))))


class ManagedProxyMixin:
    def proxy_folder(self, memory=None):
        from manager import read_vars
        memory = memory or read_vars(self.memory)
        kind = memory.get('PANEL_PROXY_KIND')
        if kind not in KINDS:return None
        folder = self.root() / kind
        if folder.is_symlink() or self.root().is_symlink() or Path(memory.get('PANEL_PROXY_DIR', '')) != folder:
            raise ValueError('面板反代目录不一致，已拒绝操作。')
        owner = json.loads((folder / 'managed.json').read_text())
        if owner != {'owner': 'vw-panel', 'kind': kind, 'root': str(self.root())}:
            raise ValueError('没有找到有效的面板反代归属记录。')
        return folder

    def proxy_settings(self):
        folder = self.proxy_folder()
        return json.loads((folder / 'settings.json').read_text()) if folder else {}

    def public_proxy(self):
        settings = self.proxy_settings()
        if not settings:return {}
        result = {key: settings.get(key) for key in ('kind', 'admin_port', 'email')}
        result['managed'] = True
        result['password_set'] = (self.proxy_folder() / 'credentials.json').exists() if settings['kind'] == 'npm' else False
        return result

    def npm_credentials(self):
        from manager import read_vars
        settings = self.proxy_settings()
        if settings.get('kind') != 'npm':raise ValueError('当前没有面板安装的 NPM。')
        credentials = json.loads((self.proxy_folder() / 'credentials.json').read_text())
        return {'email': credentials['email'], 'password': credentials['password'], 'port': settings['admin_port']}

    def prepare_proxy(self, kind, root, domain, network, email, data, existing=False):
        from manager import number, secret_text, read_vars
        if not re.fullmatch(r'[^\s@]+@[^\s@]+\.[^\s@]+', email):
            raise ValueError('安装 NPM 或 Nginx 时请填写有效的管理员邮箱，用于管理账号和 HTTPS 证书。')
        folder = root / kind
        if folder.is_symlink() or root.is_symlink():raise ValueError('反代安装目录不能是符号链接。')
        if existing:
            if self.proxy_folder() != folder:raise ValueError('反代归属记录不匹配。')
            old = json.loads((folder / 'settings.json').read_text())
        else:
            if folder.exists() and any(folder.iterdir()):raise ValueError('反代目录已有文件，已保留原配置。')
            old = {}
        settings = dict(kind=kind, domain=domain, network=network, email=email.lower())
        files = {'managed.json': json.dumps({'owner': 'vw-panel', 'kind': kind, 'root': str(root)})}
        service = {'container_name': CONTAINERS[kind], 'restart': 'unless-stopped', 'networks': [network]}
        services = {}
        if kind == 'npm':
            port = old.get('admin_port') or number(data.get('NPM_ADMIN_PORT', 8181), 'NPM 管理端口', 1024, 65535)
            settings['admin_port'] = port
            previous = json.loads((folder / 'credentials.json').read_text()) if existing else {}
            password = data.get('NPM_ADMIN_PASSWORD', '')
            if password:
                password = secret_text(password, 'NPM 管理密码')
                if len(password) < 12:raise ValueError('NPM 管理密码至少 12 个字符。')
            else:password = previous.get('password') or secrets.token_urlsafe(24)
            settings['email'] = previous.get('email') or email.lower()
            files['credentials.json'] = json.dumps({'email': settings['email'], 'password': password})
            service.update(image=NPM_IMAGE, ports=['80:80', '443:443', '%s:81' % port],
                           environment={'INITIAL_ADMIN_EMAIL': settings['email'], 'INITIAL_ADMIN_PASSWORD': password.replace('$', '$$')},
                           volumes=['./data:/data', './letsencrypt:/etc/letsencrypt'])
            services['npm'] = service
        else:
            service.update(image=NGINX_IMAGE, ports=['80:80', '443:443'],
                           volumes=['./conf.d:/etc/nginx/conf.d:ro', './webroot:/var/www/certbot:ro', './letsencrypt:/etc/letsencrypt:ro'],
                           command=['/bin/sh', '-c', "while sleep 21600; do nginx -t && nginx -s reload; done & exec nginx -g 'daemon off;'"])
            services['nginx'] = service
            services['certbot'] = {'image': CERTBOT_IMAGE, 'profiles': ['certificate'],
                'volumes': ['./webroot:/var/www/certbot', './letsencrypt:/etc/letsencrypt']}
            services['renew'] = {'image': CERTBOT_IMAGE, 'container_name': 'vw-panel-certbot', 'restart': 'unless-stopped',
                'entrypoint': ['/bin/sh', '-c'], 'command': ['trap exit TERM INT; while :; do certbot renew --webroot -w /var/www/certbot --quiet; sleep 43200 & wait $$!; done'],
                'volumes': ['./webroot:/var/www/certbot', './letsencrypt:/etc/letsencrypt']}
            files['desired.conf'] = https_nginx(domain)
            if not existing:files['conf.d/site.conf'] = bootstrap_nginx(domain)
        if not existing:ensure_proxy_ports(kind, folder, settings.get('admin_port'))
        files['settings.json'] = json.dumps(settings, sort_keys=True)
        files['docker-compose.yml'] = json.dumps({'services': services, 'networks': {network: {'external': True}}}, indent=2)
        return folder, files

    def write_proxy_plan(self, plan):
        from manager import write_private
        folder, files = plan
        for name, value in files.items():write_private(folder / name, value)
        for name in ('data', 'letsencrypt', 'webroot'):(folder / name).mkdir(exist_ok=True)

    def _npm_api_base(self):
        return 'http://127.0.0.1:%s/api/' % int(self.proxy_settings()['admin_port'])

    def _npm_request(self, path, data=None, token=None, method=None, timeout=15):
        headers = {'Content-Type': 'application/json'}
        if token:headers['Authorization'] = 'Bearer ' + token
        request = urllib.request.Request(self._npm_api_base() + path,
            data=json.dumps(data).encode() if data is not None else None, headers=headers,
            method=method or ('POST' if data is not None else 'GET'))
        # Management credentials must never follow redirects or system HTTP proxies.
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, *args, **kwargs):return None
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
        try:
            with opener.open(request, timeout=timeout) as response:
                raw = response.read(2*1024*1024+1)
                if len(raw)>2*1024*1024:raise ValueError('NPM 返回内容过大。')
                return json.loads(raw)
        except (OSError, ValueError):
            raise ValueError('NPM 请求未完成。请确认管理账号正确；申请证书时请检查 DNS 与 80 / 443 端口后重试。') from None

    def _npm_token(self):
        credentials = self.npm_credentials()
        # The API uses the original password; Compose escaping only applies to the deployment file.
        password = credentials['password']
        deadline = time.monotonic()+180
        while True:
            try:
                result = self._npm_request('tokens', {'identity': credentials['email'], 'secret': password})
                if isinstance(result, dict) and isinstance(result.get('token'), str) and result['token']:return result['token']
            except ValueError:
                pass
            if time.monotonic()>=deadline:raise ValueError('NPM 尚未就绪或管理密码不匹配。请检查代理日志；若已在 NPM 修改密码，请在配置页填写当前密码后重试。')
            time.sleep(3)

    def configure_npm(self):
        from manager import write_private
        folder = self.proxy_folder();settings = self.proxy_settings();domain = settings['domain']
        self.emit('正在等待 NPM 初始化并配置密码库 HTTPS…')
        token = self._npm_token()
        state_path = folder/'route-state.json'
        state = json.loads(state_path.read_text()) if state_path.exists() else {}
        hosts = self._npm_request('nginx/proxy-hosts', token=token)
        if not isinstance(hosts,list) or not all(isinstance(h,dict) for h in hosts):raise ValueError('NPM 站点列表格式不正确。')
        host = next((h for h in hosts if h.get('id')==state.get('host_id')), None)
        if not host and any(domain in h.get('domain_names',[]) for h in hosts):
            raise ValueError('此域名已存在于 NPM，已保留其配置。请先在 NPM 确认现有站点。')
        certificates = self._npm_request('nginx/certificates', token=token)
        if not isinstance(certificates,list) or not all(isinstance(c,dict) for c in certificates):raise ValueError('NPM 证书列表格式不正确。')
        now = datetime.datetime.now(datetime.timezone.utc)
        certificate = None
        for item in certificates:
            if item.get('provider')!='letsencrypt' or domain not in item.get('domain_names',[]):continue
            try:
                expires = datetime.datetime.fromisoformat(item.get('expires_on','').replace('Z','+00:00'))
                if expires.tzinfo is None:expires=expires.replace(tzinfo=datetime.timezone.utc)
                if expires>now:certificate=item;break
            except ValueError:pass
        if not certificate:
            self.emit('正在申请 HTTPS 证书；DNS 和端口不正确时此步骤会失败。')
            certificate = self._npm_request('nginx/certificates', {'provider':'letsencrypt','domain_names':[domain],
                'meta':{'dns_challenge':False}}, token, timeout=180)
        if not isinstance(certificate,dict) or not isinstance(certificate.get('id'),int) or certificate['id']<=0:raise ValueError('NPM 未返回有效证书。')
        payload = {'domain_names':[domain], 'forward_scheme':'http','forward_host':'vaultwarden','forward_port':80,
            'certificate_id':certificate['id'],'ssl_forced':True,'allow_websocket_upgrade':True,'http2_support':True,
            'block_exploits':False,'caching_enabled':False,'access_list_id':0,'advanced_config':'','locations':[],'meta':{},
            'hsts_enabled':False,'hsts_subdomains':False}
        if host:
            # Only the explicitly recorded host may be changed; unrelated NPM sites are untouched.
            host = self._npm_request('nginx/proxy-hosts/%s'%int(host['id']), payload, token, method='PUT')
        else:host = self._npm_request('nginx/proxy-hosts', payload, token)
        if not isinstance(host,dict) or not isinstance(host.get('id'),int) or host['id']<=0:raise ValueError('NPM 未返回有效站点。')
        write_private(state_path,json.dumps({'host_id':host['id'],'certificate_id':certificate['id'],'domain':domain}))
        if host.get('meta', {}).get('nginx_online') is False:raise ValueError('NPM 站点未能加载，请查看代理日志后重试。')
        self.emit('NPM 站点与 HTTPS 已配置，后续证书由 NPM 自动续期。')

    def deploy_managed_proxy(self, upgrade=False):
        from manager import write_private
        folder = self.proxy_folder();settings = self.proxy_settings();kind = settings['kind']
        compose = lambda *args:self.compose(folder,*args)
        if upgrade:self._command(compose('pull'))
        if kind=='npm':
            self._command(compose('up','-d','npm'))
            self.configure_npm()
        else:
            active = folder/'conf.d/site.conf';previous = active.read_text()
            domain=settings['domain'];certificate=folder/'letsencrypt/live'/domain/'fullchain.pem'
            if not certificate.exists():write_private(active,bootstrap_nginx(domain))
            try:
                self._command(compose('up','-d','nginx'))
                deadline=time.monotonic()+45
                while True:
                    try:
                        self._command(['docker','exec',CONTAINERS[kind],'test','-s','/var/run/nginx.pid'],secret=True)
                        break
                    except ValueError:
                        if time.monotonic()>=deadline:raise ValueError('Nginx 未能启动，请查看代理日志。')
                        time.sleep(1)
                if not certificate.exists():self._command(['docker','exec',CONTAINERS[kind],'nginx','-s','reload'])
                self.emit('正在申请或检查 Nginx HTTPS 证书…')
                self._command(compose('run','--rm','certbot','certonly','--webroot','-w','/var/www/certbot',
                    '--non-interactive','--agree-tos','--email',settings['email'],'--cert-name',domain,
                    '--keep-until-expiring','-d',domain))
                if not certificate.exists() or not (certificate.parent/'privkey.pem').exists():
                    raise ValueError('证书文件尚未生成，已保留此前的 Nginx 配置。')
                write_private(active,(folder/'desired.conf').read_text())
                self._command(['docker','exec',CONTAINERS[kind],'nginx','-t'])
                self._command(['docker','exec',CONTAINERS[kind],'nginx','-s','reload'])
                self._command(compose('up','-d','renew'))
            except (ValueError,OSError,subprocess.SubprocessError):
                write_private(active,previous)
                try:self._command(['docker','exec',CONTAINERS[kind],'nginx','-s','reload'])
                except (ValueError,OSError,subprocess.SubprocessError):pass
                raise
            self.emit('Nginx HTTPS 已启用，证书定时续期，Nginx 定时加载续期后的证书。')
        for container in ([CONTAINERS[kind], 'vw-panel-certbot'] if kind=='nginx' else [CONTAINERS[kind]]):
            running=self._command(['docker','inspect','--format','{{.State.Running}}',container])
            if running.strip()!='true':raise ValueError('反代或续期容器未保持运行，请查看代理日志。')
